-- Marketplace core schema for the local PostgreSQL database.
-- All money is stored as integer IQD.

create sequence if not exists public.order_number_seq start with 1001 increment by 1;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text,
  role text not null default 'buyer' check (role in ('buyer', 'seller', 'driver', 'admin')),
  city text,
  fcm_token text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint profiles_phone_iraqi_format check (phone is null or phone ~ '^07[0-9]{9}$')
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name_ku text not null unique,
  icon_name text not null default 'category',
  sort_order integer not null default 0
);

create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete restrict,
  name text not null check (length(btrim(name)) between 2 and 120),
  description text not null default '',
  category_id bigint references public.categories(id) on delete set null,
  logo_url text,
  cover_url text,
  phone text check (phone is null or phone ~ '^07[0-9]{9}$'),
  city text not null default '',
  address_text text not null default '',
  latitude double precision check (latitude is null or latitude between -90 and 90),
  longitude double precision check (longitude is null or longitude between -180 and 180),
  is_open boolean not null default false,
  is_approved boolean not null default false,
  delivery_mode text not null default 'store_self' check (delivery_mode in ('platform_driver', 'store_self')),
  delivery_fee_iqd integer not null default 2000 check (delivery_fee_iqd >= 0),
  commission_type text not null default 'percentage' check (commission_type in ('percentage', 'fixed_iqd')),
  commission_value numeric(10,2) not null default 10.00,
  created_at timestamptz not null default now(),
  constraint stores_commission_value_valid check (
    commission_value >= 0 and
    (commission_type <> 'percentage' or commission_value <= 100)
  )
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 160),
  description text not null default '',
  price_iqd integer not null check (price_iqd >= 0),
  image_url text,
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint not null unique default nextval('public.order_number_seq'),
  buyer_id uuid not null references public.profiles(id) on delete restrict,
  store_id uuid not null references public.stores(id) on delete restrict,
  driver_id uuid references public.profiles(id) on delete set null,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'preparing', 'on_the_way', 'delivered', 'rejected', 'cancelled')),
  payment_method text not null default 'cod' check (payment_method = 'cod'),
  subtotal_iqd integer not null check (subtotal_iqd >= 0),
  delivery_fee_iqd integer not null check (delivery_fee_iqd >= 0),
  total_iqd integer not null check (total_iqd >= 0),
  commission_type_snapshot text not null check (commission_type_snapshot in ('percentage', 'fixed_iqd')),
  commission_value_snapshot numeric(10,2) not null check (commission_value_snapshot >= 0),
  commission_amount_iqd integer not null check (commission_amount_iqd >= 0),
  store_net_payout_iqd integer not null check (store_net_payout_iqd >= 0),
  delivery_lat double precision,
  delivery_lng double precision,
  delivery_address text not null check (length(btrim(delivery_address)) between 1 and 500),
  buyer_note text not null default '' check (length(buyer_note) <= 500),
  buyer_phone_snapshot text not null check (buyer_phone_snapshot ~ '^07[0-9]{9}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  delivered_at timestamptz,
  constraint orders_total_consistent check (total_iqd = subtotal_iqd + delivery_fee_iqd),
  constraint orders_commission_not_over_subtotal check (commission_amount_iqd <= subtotal_iqd),
  constraint orders_net_consistent check (store_net_payout_iqd = subtotal_iqd - commission_amount_iqd),
  constraint orders_delivery_coordinates_valid check (
    (delivery_lat is null and delivery_lng is null) or
    (delivery_lat is not null and delivery_lng is not null and delivery_lat between -90 and 90 and delivery_lng between -180 and 180)
  )
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name_snapshot text not null check (length(btrim(product_name_snapshot)) between 1 and 160),
  unit_price_iqd integer not null check (unit_price_iqd >= 0),
  quantity integer not null check (quantity > 0),
  line_total_iqd integer not null check (line_total_iqd >= 0),
  constraint order_items_total_consistent check (line_total_iqd::bigint = unit_price_iqd::bigint * quantity::bigint),
  unique (order_id, product_id)
);

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete restrict,
  body text not null check (length(btrim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);

create table if not exists public.settlements (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete restrict,
  amount_iqd integer not null check (amount_iqd > 0),
  direction text not null check (direction in ('store_paid_platform', 'platform_paid_store')),
  note text not null default '' check (length(note) <= 500),
  recorded_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now()
);

create index if not exists stores_approved_city_idx on public.stores (is_approved, city, created_at desc);
create index if not exists stores_owner_idx on public.stores (owner_id, created_at desc);
create unique index if not exists stores_single_owner_idx on public.stores (owner_id);
create index if not exists stores_category_idx on public.stores (category_id, is_approved);
create index if not exists products_store_available_idx on public.products (store_id, is_available, created_at desc);
create index if not exists products_search_name_idx on public.products using gin (to_tsvector('simple', name));
create index if not exists orders_buyer_created_idx on public.orders (buyer_id, created_at desc);
create index if not exists orders_store_status_created_idx on public.orders (store_id, status, created_at desc);
create index if not exists orders_driver_status_idx on public.orders (driver_id, status, created_at desc);
create index if not exists orders_created_status_idx on public.orders (created_at desc, status);
create index if not exists order_items_order_idx on public.order_items (order_id);
create index if not exists messages_order_created_idx on public.messages (order_id, created_at);
create index if not exists settlements_store_created_idx on public.settlements (store_id, created_at desc);

-- SECURITY INVOKER ensures the view never bypasses the underlying table RLS policies.
create or replace view public.store_financial_summary
with (security_invoker = true)
as
with delivered as (
  select store_id,
         count(*)::bigint as total_delivered_orders,
         coalesce(sum(subtotal_iqd), 0)::bigint as gross_sales_iqd,
         coalesce(sum(commission_amount_iqd), 0)::bigint as total_commission_iqd
  from public.orders
  where status = 'delivered'
  group by store_id
), paid as (
  select store_id,
         coalesce(sum(case direction
           when 'store_paid_platform' then amount_iqd
           else -amount_iqd
         end), 0)::bigint as total_settled_iqd
  from public.settlements
  group by store_id
)
select s.id as store_id,
       s.name as store_name,
       coalesce(d.total_delivered_orders, 0)::bigint as total_delivered_orders,
       coalesce(d.gross_sales_iqd, 0)::bigint as gross_sales_iqd,
       coalesce(d.total_commission_iqd, 0)::bigint as total_commission_iqd,
       coalesce(p.total_settled_iqd, 0)::bigint as total_settled_iqd,
       (coalesce(d.total_commission_iqd, 0) - coalesce(p.total_settled_iqd, 0))::bigint as current_balance_due_iqd
from public.stores s
left join delivered d on d.store_id = s.id
left join paid p on p.store_id = s.id;
